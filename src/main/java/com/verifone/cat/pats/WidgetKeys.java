package com.verifone.cat.pats;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.verifone.cat.pats.runner.PatsStepError;
import com.verifone.cat.validate.PyRepr;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.util.Iterator;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Objects;
import java.util.function.Function;

/**
 * The English text of a POS widget, by its key: PATS's {@code PosActionHelper} ({@code getTopazRes}, then
 * {@code getOverlayRes}), ported from the Python {@code petrotest.pats.runner.core.widget_text}.
 *
 * <p>The tables are {@code pats/widget_keys.json} on the classpath, copied unchanged from the Python's
 * {@code src/petrotest/pats/data/widget_keys.json} (generated by {@code tools/analysis/gen_widget_keys.py} from
 * petroapps). The lookup is case-sensitive and the Topaz table wins over the overlay table, as PATS's does; a key in
 * neither is a step failure naming it.
 *
 * <p>{@link #standard()} is the lookup a handler family is constructed with (the POS UI family's
 * {@code PosUiContext} takes a {@code Function<String, String>}). The tables are read once per process.
 */
public final class WidgetKeys {

    /** The classpath resource holding the two tables. */
    public static final String RESOURCE = "/pats/widget_keys.json";

    private static final String TOPAZ = "TopazRes";
    private static final String OVERLAY = "OverlayRes";

    private static volatile Tables tables;

    private WidgetKeys() {
    }

    /** The two tables: the Topaz widgets, then the overlay widgets. */
    private record Tables(Map<String, String> topaz, Map<String, String> overlay) {
    }

    /**
     * The production lookup: {@code key} to its English text.
     *
     * @return a function that throws {@link PatsStepError} for a key in neither table
     */
    public static Function<String, String> standard() {
        return WidgetKeys::text;
    }

    /**
     * PATS's {@code getTopazRes(key)}, else {@code getOverlayRes(key)}.
     *
     * @throws PatsStepError when the key is in neither table
     */
    public static String text(String key) {
        Objects.requireNonNull(key, "key");
        Tables read = tables();
        if (read.topaz().containsKey(key)) {
            return read.topaz().get(key);
        }
        if (read.overlay().containsKey(key)) {
            return read.overlay().get(key);
        }
        throw new PatsStepError("VALIDATION KEY " + PyRepr.reprString(key)
                + " is in neither TopazRes nor OverlayRes");
    }

    private static Tables tables() {
        Tables loaded = tables;
        if (loaded == null) {
            synchronized (WidgetKeys.class) {
                loaded = tables;
                if (loaded == null) {
                    loaded = load(RESOURCE);
                    tables = loaded;
                }
            }
        }
        return loaded;
    }

    /** Reads the two tables from the classpath {@code resource}. */
    private static Tables load(String resource) {
        try (InputStream in = WidgetKeys.class.getResourceAsStream(resource)) {
            if (in == null) {
                throw new IllegalStateException("classpath resource " + resource + " is missing");
            }
            return parse(new ObjectMapper().readTree(in));
        } catch (IOException e) {
            throw new UncheckedIOException("cannot read " + resource, e);
        }
    }

    /** The tables in a parsed {@code widget_keys.json} document. */
    private static Tables parse(JsonNode document) {
        return new Tables(table(document, TOPAZ), table(document, OVERLAY));
    }

    private static Map<String, String> table(JsonNode document, String name) {
        JsonNode node = document.get(name);
        if (node == null || !node.isObject()) {
            throw new IllegalStateException("widget_keys.json has no " + name + " object");
        }
        Map<String, String> out = new LinkedHashMap<>();
        Iterator<Map.Entry<String, JsonNode>> fields = node.fields();
        while (fields.hasNext()) {
            Map.Entry<String, JsonNode> field = fields.next();
            out.put(field.getKey(), field.getValue().asText());
        }
        return Map.copyOf(out);
    }
}
