    @Test
    void everySoftKeyIsThePythonsBytes() {
        for (Map.Entry<String, String> key : PYTHON_DCR_KEYS.entrySet()) {
            assertEquals(key.getValue(), hex(ForecourtWire.encodeDcrKey(1, key.getKey())), key.getKey());
            assertEquals(key.getValue(), hex(ForecourtWire.encodeDcrKey(1, key.getKey().toLowerCase())),
                    key.getKey() + " in lower case");
        }
    }

    @Test
    void cardsKeyboardLoginsAndTheAckAreThePythonsBytes() {
        assertEquals(PYTHON_CARD_AMEX, hex(ForecourtWire.encodeDcrCard(1, "AMEXCARD")));
        assertEquals(PYTHON_CARD_MSR_DEBIT, hex(ForecourtWire.encodeDcrCard(1, "MSR DEBIT")));
        assertEquals(PYTHON_KEYBOARD_12345, hex(ForecourtWire.encodeDcrKeyboard(1, "12345")));
        assertEquals(PYTHON_DCR_LOGIN, hex(ForecourtWire.encodeLogin(false)));
        assertEquals(PYTHON_FUEL_LOGIN, hex(ForecourtWire.encodeLogin(true)));
        assertEquals(PYTHON_DCR_ACK, hex(ForecourtWire.DCR_ACK));
    }

    /** What {@link PetroDcr} writes on the suite's port, connection by connection: the login, then each key as sent. */
    @Test
    void theClientWritesTheLoginThenEachKeyOnItsOwnConnection() {
        try (Fakes.Simulator sim = new Fakes.Simulator(Fakes.fixture("dcr_ack.bin"));
                PetroDcr dcr = PetroDcr.started(HOST, 1, Fakes.freePort(), sim.port(), FAST)) {
            for (String key : PYTHON_DCR_KEYS.keySet()) {
                dcr.press(key);
            }
            dcr.insertCard("AMEXCARD");
            dcr.keyPress("12345");
            List<byte[]> sent = sim.waitFor(1 + PYTHON_DCR_KEYS.size() + 2);
            assertEquals(PYTHON_DCR_LOGIN, hex(sent.get(0)));
            int i = 1;
            for (String expected : PYTHON_DCR_KEYS.values()) {
                assertEquals(expected, hex(sent.get(i)), "connection " + i);
                i++;
            }
            assertEquals(PYTHON_CARD_AMEX, hex(sent.get(i++)));
            assertEquals(PYTHON_KEYBOARD_12345, hex(sent.get(i)));
        }
    }

    private static String hex(byte[] bytes) {
        return HexFormat.of().formatHex(bytes);
    }
